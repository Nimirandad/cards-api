package cardnumber

import "testing"

func TestValidateLuhn(t *testing.T) {
	t.Run("validates a correct Luhn number", func(t *testing.T) {
		if !ValidateLuhn("4539578763621486") {
			t.Fatalf("expected number to pass Luhn, got false")
		}
	})
	t.Run("invalidates an incorrect Luhn number", func(t *testing.T) {
		if ValidateLuhn("4539578763621487") {
			t.Fatalf("expected number to fail Luhn, got true")
		}
	})

	t.Run("validates a number generated by GenerateCardNumber", func(t *testing.T) {
		card, err := GenerateCardNumber()
		if err != nil {
			t.Fatalf("expected no error, got %v", err)
		}
		if !ValidateLuhn(card) {
			t.Fatalf("expected generated number to pass Luhn, got %s", card)
		}
	})

	t.Run("invalidates a number with incorrect length", func(t *testing.T) {
		if ValidateLuhn("123456789012345") {
			t.Fatalf("expected number to fail Luhn due to incorrect length, got true")
		}
	})
}

func TestAppendLuhnCheckDigit(t *testing.T) {
	t.Run("appends a correct Luhn check digit", func(t *testing.T) {
		body := "453957876362148"
		full, err := AppendLuhnCheckDigit(body)
		if err != nil {
			t.Fatalf("expected no error, got %v", err)
		}
		if !ValidateLuhn(full) {
			t.Fatalf("expected full number to pass Luhn, got %s", full)
		}
	})

	t.Run("returns an error for an empty body", func(t *testing.T) {
		_, err := AppendLuhnCheckDigit("")
		if err == nil {
			t.Fatalf("expected error for empty body, got nil")
		}
	})
}
